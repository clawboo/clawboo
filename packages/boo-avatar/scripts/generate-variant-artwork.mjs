#!/usr/bin/env node
/**
 * Embeds the locked Boo variant artwork into TypeScript string modules.
 *
 *   node scripts/generate-variant-artwork.mjs [sourceDir]
 *   BOO_VARIANTS_DIR=/path/to/clawboo-boo-variants node scripts/generate-variant-artwork.mjs
 *
 * The artwork is approved brand work that lives OUTSIDE this repo, in the design folder
 * `clawboo-boo-variants` (a sibling of the repo checkout by default). That folder's LOCKED.md
 * records a sha256 per file; the same hashes are listed below, and a file whose bytes do not
 * match its hash is refused rather than embedded. Each generated module re-exports its hash so
 * `src/variants/__tests__/artwork.test.ts` can recompute it over the embedded string: that is
 * what catches a hand edit of the SVG after it was embedded.
 *
 * Regenerate only to pick up a re-locked SVG, and update the hash here in the same change.
 */
import { createHash } from 'node:crypto'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

import prettier from 'prettier'

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const outDir = join(packageRoot, 'src', 'variants', 'artwork')

/** The design folder sits beside the repo checkout, not inside it. */
const DEFAULT_SOURCE_DIR = resolve(packageRoot, '..', '..', '..', 'clawboo-boo-variants')

const ARTWORK = [
  {
    module: 'codex',
    file: 'codex/codex-boo.svg',
    constant: 'CODEX_BOO_SVG',
    label: 'Codex Boo',
    sha256: '90e9e9a29327443a1cec87395b1e7da6841d4f3e4c96da1453003058ce40c335',
  },
  {
    module: 'claude',
    file: 'claude/claude-boo.svg',
    constant: 'CLAUDE_BOO_SVG',
    label: 'Claude Boo',
    sha256: 'e09b7bbb66e7d97ecdd41c08b83c838823b5a77df30fc33cce98eb17e3bb97e6',
  },
  {
    module: 'hermes-light',
    file: 'hermes/hermes-boo.svg',
    constant: 'HERMES_BOO_LIGHT_SVG',
    label: 'Hermes Boo, light surfaces',
    sha256: 'b685127cd7ee51bdc157e63f7a3604dbc1948d563887298d48f991e0581eca47',
  },
  {
    module: 'hermes-dark',
    file: 'hermes/hermes-boo-dark.svg',
    constant: 'HERMES_BOO_DARK_SVG',
    label: 'Hermes Boo, dark surfaces',
    sha256: '097abd4cd93ab886f0d57ca531567e3c509e6923a0fc7be449ce95253055d5d9',
  },
]

const sha256 = (text) => createHash('sha256').update(text, 'utf8').digest('hex')

/**
 * A single-quoted JS string literal holding `text` verbatim.
 *
 * The locked SVGs carry no backslash, no apostrophe and no CR, so these three escapes are the
 * whole job; they are written out anyway so re-locked artwork that gains one still embeds
 * exactly. Newlines become `\n` because the literal has to stay on one line: the bytes are
 * hashed, so a line break prettier introduced would change the artwork.
 */
const literal = (text) =>
  `'${text.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\r/g, '\\r').replace(/\n/g, '\\n')}'`

const sourceDir = resolve(process.argv[2] ?? process.env.BOO_VARIANTS_DIR ?? DEFAULT_SOURCE_DIR)

const prettierOptions = await prettier.resolveConfig(join(outDir, 'codex.ts'))

for (const art of ARTWORK) {
  const path = join(sourceDir, art.file)
  const svg = readFileSync(path, 'utf8')
  const digest = sha256(svg)
  if (digest !== art.sha256) {
    throw new Error(
      `${art.file} hashes to ${digest}, not the locked ${art.sha256}. Either the artwork was ` +
        're-locked (update the hash here in the same change) or the file has been edited.',
    )
  }
  const source = [
    `// Generated by packages/boo-avatar/scripts/generate-variant-artwork.mjs. Do not edit by hand.`,
    `//`,
    `// ${art.label}, embedded verbatim from the locked design folder's ${art.file}.`,
    `// The SVG is one string on one line on purpose: its bytes are hashed, so a line break would`,
    `// change the artwork. Import it only from a variant module, never from the package root.`,
    ``,
    `/** sha256 of ${art.constant}, as locked in clawboo-boo-variants/LOCKED.md. */`,
    `export const ${art.constant}_SHA256 = '${art.sha256}'`,
    ``,
    `export const ${art.constant} = ${literal(svg)}`,
    ``,
  ].join('\n')
  const formatted = await prettier.format(source, {
    ...prettierOptions,
    parser: 'typescript',
  })
  mkdirSync(outDir, { recursive: true })
  const out = join(outDir, `${art.module}.ts`)
  writeFileSync(out, formatted)
  console.log(`${art.module}.ts  ${svg.length} bytes  ${digest.slice(0, 12)}`)
}
